"use client";

import { useActionState, useState, useTransition } from "react";
import { Button } from "@/components/ui/button";
import { FormMessage, SubmitButton, TextField } from "@/components/ui/form-kit";
import { idleState } from "@/modules/core/validation";
import { startTotpEnrollmentAction, verifyTotpAction, type EnrollState } from "@/app/account/actions";

function CodeForm({
  factorId,
  mode,
  next,
  submitLabel,
}: {
  factorId: string;
  mode: "enrol" | "verify";
  next?: string;
  submitLabel: string;
}) {
  const [state, action] = useActionState(verifyTotpAction, idleState);
  return (
    <form action={action} className="flex flex-col gap-4" noValidate>
      <FormMessage state={state} />
      <input type="hidden" name="factorId" value={factorId} />
      <input type="hidden" name="mode" value={mode} />
      <input type="hidden" name="next" value={next ?? ""} />
      <TextField
        name="code"
        label="6-digit code"
        inputMode="numeric"
        autoComplete="one-time-code"
        pattern="[0-9]{6}"
        maxLength={6}
        required
        state={state}
      />
      <SubmitButton className="self-start">{submitLabel}</SubmitButton>
    </form>
  );
}

/** First-time authenticator-app setup: QR code + manual secret + confirmation code. */
export function TotpEnrollment({ next }: { next?: string }) {
  const [enroll, setEnroll] = useState<EnrollState>({ status: "idle" });
  const [pending, startTransition] = useTransition();

  if (enroll.status === "enrolling") {
    return (
      <div className="flex flex-col gap-6">
        <ol className="list-decimal space-y-2 pl-5 text-sm">
          <li>Open an authenticator app (for example Google Authenticator, Microsoft Authenticator or 1Password).</li>
          <li>Scan the QR code, or enter the setup key manually.</li>
          <li>Enter the 6-digit code the app shows.</li>
        </ol>
        {/* eslint-disable-next-line @next/next/no-img-element -- data: URI SVG generated by the auth server */}
        <img
          src={enroll.qrCode}
          alt="QR code for your authenticator app"
          width={192}
          height={192}
          className="border-rule border bg-white p-2"
        />
        <div>
          <p className="text-sm font-medium">Setup key</p>
          <code className="bg-ink/5 mt-1 block px-3 py-2 font-mono text-sm break-all">{enroll.secret}</code>
        </div>
        <CodeForm factorId={enroll.factorId} mode="enrol" next={next} submitLabel="Confirm and turn on" />
      </div>
    );
  }

  return (
    <div className="flex flex-col gap-4">
      {enroll.status === "error" ? <FormMessage state={{ status: "error", message: enroll.message }} /> : null}
      <Button
        type="button"
        className="self-start"
        loading={pending}
        onClick={() => startTransition(async () => setEnroll(await startTotpEnrollmentAction()))}
      >
        Set up authenticator app
      </Button>
    </div>
  );
}

/** Step-up verification for an existing factor (upgrades the session to aal2). */
export function TotpChallenge({ factorId, next }: { factorId: string; next?: string }) {
  return <CodeForm factorId={factorId} mode="verify" next={next} submitLabel="Verify" />;
}
